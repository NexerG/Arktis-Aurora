# Converts Computer Modern .tfm files into the math metrics TeX documents use: each character's width and italic
# correction in em, keyed by Unicode, per design size.
# Usage: TfmToAxml.py <folder of .tfm> <out.axml>   (sources: https://mirrors.ctan.org/fonts/cm/tfm/)
import os, struct, sys
from xml.sax.saxutils import quoteattr

GREEK_UPPER = "ΓΔΘΛΞΠΣΥΦΨΩ"
# OML (cmmi): Greek 11-39, punctuation 58-62, letters
OML = {i: c for i, c in enumerate(GREEK_UPPER)}
OML.update({11 + i: c for i, c in enumerate("αβγδϵζηθικλμνξπρστυϕχψωεϑϖϱςφ")})
OML.update({58: ".", 59: ",", 60: "<", 61: "/", 62: ">", 64: "∂", 96: "ℓ", 123: "ı", 124: "ȷ"})
OML.update({c: chr(c) for c in range(65, 91)})
OML.update({c: chr(c) for c in range(97, 123)})
# OT1 (cmr): upright Greek, digits, letters and the punctuation math takes from it
OT1 = {i: c for i, c in enumerate(GREEK_UPPER)}
OT1.update({c: chr(c) for c in b"!()+:;=?[]"})
OT1.update({c: chr(c) for c in range(48, 58)})
OT1.update({c: chr(c) for c in range(65, 91)})
OT1.update({c: chr(c) for c in range(97, 123)})
# OMS (cmsy): operators, relations, arrows, delimiters
OMS = dict(enumerate("−⋅×∗÷⋄±∓⊕⊖⊗⊘⊙◯∘∙≍≡⊆⊇≤≥⪯⪰∼≈⊂⊃≪≫≺≻←→↑↓↔↗↘≃⇐⇒⇑⇓⇔↖↙∝′∞∈∋△▽"))
OMS.update({56: "∀", 57: "∃", 58: "¬", 59: "∅", 60: "ℜ", 61: "ℑ", 62: "⊤", 63: "⊥", 64: "ℵ"})
OMS.update({91 + i: c for i, c in enumerate("∪∩⊎∧∨⊢⊣⌊⌋⌈⌉{}⟨⟩|‖↕⇕∖≀√⨿∇")})
OMS.update({116 + i: c for i, c in enumerate("⊔⊓⊑⊒§†‡¶♣♢♡♠")})
FAMILIES = (("cmmi", "MathItalic", OML), ("cmr", "Roman", OT1), ("cmsy", "Symbol", OMS))
# OMX (cmex): big operators, text size then display size
OMX = {0x46: "⨆", 0x48: "∮", 0x4A: "⨀", 0x4C: "⨁", 0x4E: "⨂", 0x50: "∑", 0x51: "∏", 0x52: "∫", 0x53: "⋃", 0x54: "⋂",
       0x55: "⨄", 0x56: "⋀", 0x57: "⋁", 0x60: "∐"}
OMX_DISPLAY = {0x47: "⨆", 0x49: "∮", 0x4B: "⨀", 0x4D: "⨁", 0x4F: "⨂", 0x58: "∑", 0x59: "∏", 0x5A: "∫", 0x5B: "⋃",
               0x5C: "⋂", 0x5D: "⨄", 0x5E: "⋀", 0x5F: "⋁", 0x61: "∐"}


def read(path):
    data = open(path, "rb").read()
    lf, lh, bc, ec, nw, nh, nd, ni, nl, nk, ne, np = struct.unpack(">12H", data[:24])
    words = struct.unpack(">%di" % lf, data[:lf * 4])
    fix = lambda w: w / float(1 << 20)
    design = fix(words[6 + 1])
    info = 6 + lh
    widths = info + ec - bc + 1
    heights = widths + nw
    depths = heights + nh
    italics = depths + nd
    chars = {}
    for code in range(bc, ec + 1):
        w = words[info + code - bc]
        wi, hi, di, ii = (w >> 24) & 0xFF, (w >> 20) & 0xF, (w >> 16) & 0xF, (w >> 10) & 0x3F
        if wi == 0: continue
        chars[code] = (fix(words[widths + wi]), fix(words[italics + ii]), fix(words[heights + hi]), fix(words[depths + di]))
    return design, chars


def main(folder, out):
    lines = ['<?xml version="1.0" encoding="utf-8" ?>',
             "<!-- Generated by _Build/TfmToAxml.py from Computer Modern .tfm files (CTAN fonts/cm/tfm). Width, Italic, Height and Depth in em. -->",
             "<ComputerModern>"]
    for prefix, family, table in FAMILIES:
        names = sorted((f[:-4] for f in os.listdir(folder) if f.startswith(prefix) and f.endswith(".tfm") and f[len(prefix):-4].isdigit()),
                       key=lambda n: int(n[len(prefix):]))
        for name in names:
            design, chars = read(os.path.join(folder, name + ".tfm"))
            lines.append('\t<Font Name="%s" Family="%s" Size="%g">' % (name, family, design))
            for code in sorted(chars):
                if code not in table: continue
                width, italic, height, depth = chars[code]
                lines.append('\t\t<Char Code=%s Width="%.6f" Italic="%.6f" Height="%.6f" Depth="%.6f"/>'
                             % (quoteattr(table[code]), width, italic, height, depth))
            lines.append("\t</Font>")
    # big operators: the box TeX centres on the axis, Height and Depth in em
    design, chars = read(os.path.join(folder, "cmex10.tfm"))
    lines.append('\t<Font Name="cmex10" Family="Extension" Size="%g">' % design)
    for size, table in (("Text", OMX), ("Display", OMX_DISPLAY)):
        for code in sorted(table):
            width, italic, height, depth = chars[code]
            lines.append('\t\t<Char Code=%s Style="%s" Width="%.6f" Italic="%.6f" Height="%.6f" Depth="%.6f"/>'
                         % (quoteattr(table[code]), size, width, italic, height, depth))
    lines.append("\t</Font>")
    lines.append("</ComputerModern>")
    with open(out, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
